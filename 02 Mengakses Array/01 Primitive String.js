// Primitive String

// Deklarasi string
let nama = "John Doe";
let pesan = 'Halo, selamat datang!';
console.log(nama);
console.log(pesan);

// Penggabungan (Concatenation)
let namaLengkap = 'John'+' '+'Doe';
console.log(namaLengkap); // Output: John Doe

// Mengakses Karakter dalam Indeks
let namaAkses = 'John';
console.log(namaAkses[0]); // Output: J